// Writes supabase/seed.sql from features/goonj/campaigns/defaults.ts.
// Run: node scripts/goonj-seed.mjs
import { writeFileSync } from "node:fs";
import { DEFAULT_PAGE } from "../features/goonj/campaigns/defaults.ts";

const q = (v) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
const s = (v) => `'${v.replace(/'/g, "''")}'`;

const rows = [
  { slug: DEFAULT_PAGE.slug, name: "Limited release (default page)", kind: "default", status: "published", tpl: false, ...DEFAULT_PAGE },
  {
    slug: "sample-avika",
    name: "Sample: Avika (influencer)",
    kind: "influencer",
    status: "draft",
    tpl: true,
    hero: {
      ...DEFAULT_PAGE.hero,
      badge: undefined,
      title: "Hi, I'm Avika. This is how I practise for work.",
      titleAccent: "how I practise for work.",
      creator: { name: "Avika", handle: "@sample.avika" },
      media: { ...DEFAULT_PAGE.hero.media, alt: "Sample photo (replace with the creator's photo)" },
    },
    form: {
      ...DEFAULT_PAGE.form,
      fields: DEFAULT_PAGE.form.fields.filter((f) => f.key === "first_name" || f.key === "email"),
    },
    points: DEFAULT_PAGE.points,
    seo: { title: "Avika × Goonj (sample)" },
  },
  {
    slug: "sample-diwali",
    name: "Sample: Diwali (seasonal)",
    kind: "seasonal",
    status: "draft",
    tpl: true,
    hero: { ...DEFAULT_PAGE.hero, badge: "Diwali release", title: "This Diwali, give your career a brighter start.", titleAccent: "a brighter start." },
    form: DEFAULT_PAGE.form,
    points: DEFAULT_PAGE.points,
    seo: { title: "Goonj this Diwali (sample)" },
  },
];

const sql = [
  "-- Generated by scripts/goonj-seed.mjs from defaults.ts. Samples are drafts, clearly labelled.",
  ...rows.map(
    (r) =>
      `insert into public.goonj_campaigns (slug, name, kind, status, is_template, hero, form, points, seo) values (${s(r.slug)}, ${s(r.name)}, ${s(r.kind)}, ${s(r.status)}, ${r.tpl}, ${q(r.hero)}, ${q(r.form)}, ${q(r.points)}, ${q(r.seo)}) on conflict (slug) do nothing;`,
  ),
  "",
].join("\n");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("wrote supabase/seed.sql", rows.length, "rows");
